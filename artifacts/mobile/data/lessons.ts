export function getOrderedLessons(lessons: Lesson[] = LESSONS): Lesson[] {
  return [...lessons].sort((a, b) => {
    const levelCompare = LEVELS.findIndex((level) => level.id === a.level) -
      LEVELS.findIndex((level) => level.id === b.level);
    if (levelCompare !== 0) return levelCompare;

    const aOrder = LESSON_PATH_ORDER[a.id] ?? 999;
    const bOrder = LESSON_PATH_ORDER[b.id] ?? 999;
    if (aOrder !== bOrder) return aOrder - bOrder;

    return LESSONS.indexOf(a) - LESSONS.indexOf(b);
  });
}

